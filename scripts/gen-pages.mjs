const TIER_LABEL = { core: 'Core', deepen: 'Deepen', reference: 'Reference' };
const WEIGHT_LABEL = { S: 'Short', M: 'Medium', L: 'Long' };
const FLAG_LABEL = {
	caveat: 'Caveat',
	lifelong: 'Lifelong',
	free: 'Free',
	ground: 'My ground',
};
const FLAG_GLYPH = { caveat: '⚠', lifelong: '∞', free: 'Free', ground: 'NP' };

const chip = (cls, text, title) =>
	`<span class="ds-chip ${cls}"${title ? ` title="${esc(title)}"` : ''}>${esc(text)}</span>`;

function bookCard(book, href) {
	const chips = [
		chip(`ds-chip--tier-${book.tier}`, TIER_LABEL[book.tier], `${TIER_LABEL[book.tier]} — see the legend`),
		chip('ds-chip--weight', book.weight, WEIGHT_LABEL[book.weight]),
		...book.flags.map((f) => chip(`ds-chip--flag ds-chip--flag-${f}`, FLAG_GLYPH[f], FLAG_LABEL[f])),
	].join('');

	const title = href
		? `<a class="ds-card__link" href="${href}">${esc(book.title)}</a>`
		: esc(book.title);

	const byline = [book.author, book.edition && `(${book.edition})`].filter(Boolean).join(' ');

	return [
		`<div class="ds-card ds-book${href ? '' : ' ds-card--empty'}" data-tier="${book.tier}" data-weight="${book.weight}">`,
		`<h3 class="ds-card__title">${title}</h3>`,
		byline ? `<div class="ds-card__byline">${inlineMd(byline)}</div>` : '',
		`<div class="ds-card__body">${inlineMd(book.why)}</div>`,
		`<div class="ds-card__meta">${chips}</div>`,
		`</div>`,
	]
		.filter(Boolean)
		.join('\n');
}

function plainCard({ href, title, body, meta }) {
	return [
		`<div class="ds-card${href ? '' : ' ds-card--empty'}">`,
		`<h3 class="ds-card__title">${href ? `<a class="ds-card__link" href="${href}">${esc(title)}</a>` : esc(title)}</h3>`,
		body ? `<div class="ds-card__body">${inlineMd(body)}</div>` : '',
		meta ? `<div class="ds-card__meta">${meta}</div>` : '',
		`</div>`,
	]
		.filter(Boolean)
		.join('\n');
}

const grid = (cards) => `<div class="ds-grid">\n\n${cards.join('\n\n')}\n\n</div>`;

/** Counts, shown as chips. Deliberately NOT a count of books read: the
 *  reconciliation (row 9) puts no reading counter anywhere in the chrome.
 *
 *  A ZERO IS OMITTED, NOT SHOWN. MEASURED 2026-09-01: a cluster with no core
 *  book — real, and not rare; a cluster can be all deepen and reference —
 *  rendered "0 core" beside its two real counts. A count exists to tell you
 *  how much of something there is; "0 core" tells you there is none, which is
 *  what its ABSENCE already says on every other row. Whichever tiers are
 *  actually present still render in their fixed order, so "2 deepen · 1
 *  reference" reads as a complete answer rather than a row with a hole in it.
 */
function tierCounts(books) {
	const n = (t) => books.filter((b) => b.tier === t).length;
	return [
		n('core') && chip('ds-chip--count ds-chip--tier-core', `${n('core')} core`),
		n('deepen') && chip('ds-chip--count ds-chip--tier-deepen', `${n('deepen')} deepen`),
		n('reference') && chip('ds-chip--count ds-chip--tier-reference', `${n('reference')} reference`),
	]
		.filter(Boolean)
		.join('');
}


const BANNER =
	'{/* GENERATED by scripts/gen-pages.mjs from context/universe.md. Do not hand-edit. */}';

/*
 * The method pages are `.md`, NOT `.mdx`, and that is a deliberate engineering
 * choice rather than an inconsistency with the rest of the project.
 *
 * They are VERBATIM copies of four hand-written documents in context/, and
 * between them those documents contain 38 bare `<` characters in ordinary prose
 * ("<30% degradation", "d < 0.2", "<BOOK>"). In .mdx every one of those is the
 * start of a JSX tag and a hard build error. In .md it is a literal.
 *
 * The project's ".mdx only" rule governs AUTHORED pages, where the components
 * are the point. Nothing here authors anything: escaping a copy to satisfy a
 * rule aimed at a different problem would mean the published text no longer
 * matches the file it came from, which is the one property these pages have.
 *
 * Consequence to know: no components, and the comment syntax is HTML.
 */
const MD_BANNER =
	'<!-- GENERATED by scripts/gen-pages.mjs from context/. Do not hand-edit: edit the source. -->';

/* --------------------------------------------------------------------------
 * Text
 * ------------------------------------------------------------------------ */

/** HTML-escape, INCLUDING `{`, which MDX reads as the start of an expression. */
const esc = (s) =>
	String(s)
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;')
		.replace(/\{/g, '&#123;')
		.replace(/\}/g, '&#125;');

/**
 * The smallest possible inline-Markdown renderer, for the `why` lines, which
 * carry **bold**, *italic* and `code`.
 *
 * ESCAPES FIRST, then marks up, so nothing in the source file can inject HTML.
 * Handles three constructs and must not grow into a parser.
 */
function inlineMd(raw) {
	let s = esc(raw);
	s = s.replace(/`([^`]+)`/g, '<code>$1</code>');
	s = s.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>'); // bold before italic
	s = s.replace(/\*([^*]+)\*/g, '<em>$1</em>');
	return s;
}

/** Quote and escape in one step. */
const yaml = (v) => JSON.stringify(String(v));

/** Truncate at a word boundary. */
function clamp(s, n) {
	const t = String(s).replace(/\s+/g, ' ').trim();
	if (t.length <= n) return t;
	return t.slice(0, t.lastIndexOf(' ', n)).replace(/[,;:.—-]+$/, '') + '…';
}


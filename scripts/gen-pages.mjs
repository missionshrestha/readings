function page({ title, description, body, headTitle }) {
	const fm = [
		'---',
		`title: ${yaml(title)}`,
		`description: ${yaml(description)}`,
		'template: splash',
		'tableOfContents: false',
	];
	if (headTitle) {
		// Starlight builds <title> as "<page> | <site>", which on the home page
		// renders "Readings | Readings".
		fm.push('head:', '  - tag: title', `    content: ${yaml(headTitle)}`);
	}
	fm.push('---');
	return `${fm.join('\n')}\n${BANNER}\n\n${body}\n`;
}

function write(relPath, contents) {
	const full = join(DOCS, relPath);
	mkdirSync(dirname(full), { recursive: true });
	writeFileSync(full, contents);
}


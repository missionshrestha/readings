// Remove previously generated map pages so a renamed slug cannot leave an
// orphan behind. Only files carrying the banner are removed — a book directory
// is never touched.
let removed = 0;
function pruneGenerated(dir) {
	if (!existsSync(dir)) return;
	for (const entry of readdirSync(dir)) {
		const full = join(dir, entry);
		if (statSync(full).isDirectory()) pruneGenerated(full);
		else if (entry === 'index.mdx' && readFileSync(full, 'utf8').includes(BANNER)) {
			rmSync(full);
			removed++;
		}
		// The method pages are .md and carry the HTML-comment banner. Pruned by the
		// same rule so a renamed slug cannot strand an orphan that still builds.
		else if (entry.endsWith('.md') && readFileSync(full, 'utf8').includes(MD_BANNER)) {
			rmSync(full);
			removed++;
		}
	}
}
pruneGenerated(DOCS);
if (existsSync(join(DOCS, 'index.mdx')) && readFileSync(join(DOCS, 'index.mdx'), 'utf8').includes('PLACEHOLDER'))
	rmSync(join(DOCS, 'index.mdx'));

write('index.mdx', homePage(u, started));
let pages = 1;

// The method pages. Written BEFORE the map pages so a failure to read one of
// the four sources aborts the run rather than leaving a half-generated tree.
write(join('method', 'index.mdx'), methodHub());
for (const m of METHOD) write(join('method', `${m.slug}.md`), methodPage(m));
for (const d of u.domains) {
	write(join(d.slug, 'index.mdx'), domainPage(d));
	pages++;
	for (const c of d.clusters) {
		write(join(d.slug, c.slug, 'index.mdx'), clusterPage(c, d, started));
		pages++;
	}
}

mkdirSync(GENERATED, { recursive: true });

// The flat slug -> label map the breadcrumb imports.
const labels = { domains: {}, clusters: {}, books: {} };
for (const d of u.domains) {
	labels.domains[d.slug] = d.displayName;
	for (const c of d.clusters) {
		labels.clusters[`${d.slug}/${c.slug}`] = `${c.number} · ${c.name}`;
		for (const b of c.books) labels.books[`${d.slug}/${c.slug}/${b.slug}`] = b.title;
	}
}

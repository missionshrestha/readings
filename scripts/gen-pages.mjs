/* --------------------------------------------------------------------------
 * On-disk state — which books have actually been started
 * ------------------------------------------------------------------------ */

function startedBooks() {
	const started = new Set();
	if (!existsSync(DOCS)) return started;
	for (const d of readdirSync(DOCS)) {
		const dd = join(DOCS, d);
		if (!existsSync(dd) || !statSync(dd).isDirectory()) continue;
		for (const c of readdirSync(dd)) {
			const cc = join(dd, c);
			if (!statSync(cc).isDirectory()) continue;
			for (const b of readdirSync(cc)) {
				const bb = join(cc, b);
				if (statSync(bb).isDirectory() && existsSync(join(bb, 'index.mdx')))
					started.add(`${d}/${c}/${b}`);
			}
		}
	}
	return started;
}


/**
 * gen-pages.mjs — the three map levels, GENERATED. Never hand-edit the output.
 *
 *   /                        7 part sections, 16 domain cards
 *   /<domain>/               clusters as cards                    x 16
 *   /<domain>/<cluster>/     every book as a card, live or not    x 85
 *
 * plus four derived artifacts:
 *
 *   src/generated/universe.json    the parsed tree, for anything that needs it
 *   src/generated/nav-labels.json  slug -> label, IMPORTED by the breadcrumb
 *   src/generated/book-slugs.md    293 rows, handed to web chat as knowledge
 *   public/_redirects              re-cluster redirects, header only until used
 *
 * A book's own directory is written by scripts/new-book.mjs, never here.
 *
 * ---------------------------------------------------------------------------
 * WHY nav-labels.json IS IMPORTED RATHER THAN READ
 *
 * The breadcrumb override first called parseUniverse() directly. That works in
 * `dev` and fails in `build`: the component is bundled into dist/.prerender/,
 * so the relative path to context/universe.md resolves against the bundle and
 * throws ENOENT at render time. A build-time file read does not survive
 * bundling into the render context. An imported JSON module does — the bundler
 * inlines it.
 *
 * ---------------------------------------------------------------------------
 * WHY RAW HTML AND NOT <LinkCard>
 *
 * A book that has not been started has NOWHERE TO GO. A <LinkCard> must have an
 * href; saying "not started" by not being a link is more honest than a link
 * that does nothing. So a card is a <div> whose title is an <a> only when the
 * book's directory actually exists on disk.
 *
 * Block containers are <div>, never <p>. Markdown wraps multi-line content in a
 * <p> of its own, and a <p> inside a <p> is invalid HTML that browsers silently
 * restructure — with the build exiting 0 throughout.
 */


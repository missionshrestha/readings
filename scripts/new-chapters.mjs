function readChapterFrontmatter(dir) {
	if (!existsSync(dir)) return [];
	return readdirSync(dir)
		.filter((f) => f.endsWith('.mdx') && f !== 'index.mdx' && !f.startsWith('_'))
		.map((file) => {
			const raw = readFileSync(join(dir, file), 'utf8');
			const open = raw.indexOf('---');
			const close = raw.indexOf('\n---', open + 3);
			const fm = close === -1 ? '' : raw.slice(open + 3, close);
			const f = (n) => {
				const m = fm.match(new RegExp(`^${n}:\\s*(.+)$`, 'm'));
				return m ? m[1].trim().replace(/^["']|["']$/g, '') : undefined;
			};
			const orderM = fm.match(/^\s+order:\s*(\d+)\s*$/m);
			return {
				slug: file.replace(/\.mdx$/, ''),
				title: f('title') ?? file,
				part: f('part') ?? '',
				status: f('status') ?? 'stub',
				draft: f('draft') === 'true',
				/*
				 * `private` IS READ FOR THE SAME REASON `draft` IS, and it was missing.
				 * See chaptersBlock() — a private chapter that has been flipped out of
				 * draft is a real, non-draft file, so the grid linked it.
				 */
				private: f('private') === 'true',
				order: orderM ? Number(orderM[1]) : Number.POSITIVE_INFINITY,
			};
		})
		.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));
}

/* ---- validation ---------------------------------------------------------- */

function validate(raw) {
	const problems = [];
	const warnings = [];
	const fault = (m) => problems.push(m);
	const advisory = (m) => warnings.push(m);

	if (!raw || typeof raw !== 'object' || Array.isArray(raw))
		return { problems: ['book.json is not an object. See context/book-spec.md §2.'], warnings };

	for (const f of ['slug', 'title', 'kind'])
		if (!raw[f]) fault(`missing "${f}"`);
	if (raw.slug && raw.slug !== bookSlug)
		fault(`"slug" is "${raw.slug}" but the directory is "${bookSlug}" — the path is the truth`);
	if (raw.domain && raw.domain !== domainSlug)
		fault(`"domain" is "${raw.domain}" but the directory says "${domainSlug}"`);
	if (raw.cluster && raw.cluster !== clusterSlug)
		fault(`"cluster" is "${raw.cluster}" but the directory says "${clusterSlug}"`);

	/*
	 * THE RELEASE DATE AND THE MAJOR EDITIONS, on all three kinds — so before the
	 * `kind !== 'read'` return below. His instruction, 2026-09-14: every book
	 * displays them, and src/overrides/PageTitle.astro reads them from this file.
	 * scripts/book-dates.mjs holds the formats and the exact messages.
	 */
	const dates = checkBookDates(raw);
	problems.push(...dates.problems);
	warnings.push(...dates.warnings);

	if (!raw.gap) fault('missing "gap" — knowledge or execution. Spec §2, and it comes before everything');
	else if (!GAPS.includes(raw.gap)) fault(`"gap" is "${raw.gap}", must be ${GAPS.join(' or ')}`);

	if (raw.familiarity && !FAMILIARITY.includes(raw.familiarity))
		fault(`"familiarity" is "${raw.familiarity}", must be one of ${FAMILIARITY.join(', ')}`);

	if (!raw.exitCondition) fault('missing "exitCondition" — what must be TRUE for this book to be finished');
	if (!Array.isArray(raw.questions) || raw.questions.length < 3)
		fault('"questions" needs 3-5 entries, written BEFORE reading. Written after, they are a summary');

	if (raw.kind !== 'read') {
		if (raw.chapters?.length) fault(`kind "${raw.kind}" carries no chapters`);
		return { problems, warnings };
	}

	if (!Array.isArray(raw.chapters) || raw.chapters.length === 0)
		return { problems: [...problems, 'no "chapters" array'], warnings };

	const partSlugs = new Set((raw.parts ?? []).map((p) => p.slug));
	for (const p of raw.parts ?? []) {
		if (!KEBAB.test(p.slug ?? '')) fault(`part slug "${p.slug}" is not kebab-case`);
		if (!p.outcome) fault(`part "${p.slug}" has no "outcome"`);
	}

	const seen = new Set();
	const orders = new Set();
	for (const c of raw.chapters) {
		const at = `chapter "${c.slug ?? c.title ?? '?'}"`;
		if (!KEBAB.test(c.slug ?? '')) fault(`${at}: slug is missing or not kebab-case`);
		if (seen.has(c.slug)) fault(`${at}: slug repeats`);
		seen.add(c.slug);
		if (!Number.isInteger(c.order)) fault(`${at}: "order" must be an integer`);
		else if (orders.has(c.order)) fault(`${at}: order ${c.order} repeats`);
		else orders.add(c.order);
		if (!c.title) fault(`${at}: no title`);
		// A label replaces the NUMBER, never the title. See chapterNumbers().
		if (c.label !== undefined) {
			const label = typeof c.label === 'string' ? c.label.trim() : '';
			if (!label)
				fault(`${at}: "label" must be text like "Introduction" — or absent, on a numbered chapter`);
			else if (/\d|·/.test(label) || /^ch(apter)?\b/i.test(label))
				fault(`${at}: label "${label}" carries a number — a numbered chapter has no label, and the site numbers it`);
			else if (c.title && String(c.title).trim().toLowerCase() === label.toLowerCase())
				fault(`${at}: title is just "${c.title}" — the label already shows that. The title says what it argues`);
		}
		if (!c.argues) fault(`${at}: no "argues" — one line, a CLAIM rather than a topic`);
		if (c.part && !partSlugs.has(c.part)) fault(`${at}: part "${c.part}" is not in "parts"`);
		if (c.verdict && !VERDICTS.includes(c.verdict))
			fault(`${at}: verdict "${c.verdict}", must be one of ${VERDICTS.join(', ')}`);
		if (c.verdict === 'skip')
			fault(`${at}: verdict "skip" — a skipped chapter belongs in "antiChapters", not "chapters"`);
		if (c.weightInArgument && !WEIGHTS_IN_ARG.includes(c.weightInArgument))
			fault(`${at}: weightInArgument "${c.weightInArgument}", must be one of ${WEIGHTS_IN_ARG.join(', ')}`);
		if (typeof c.clarified !== 'boolean')
			fault(`${at}: "clarified" must be true or false — a deliberate value, not a default nobody looked at`);
	}

	// THE COVERAGE LAW. Asserted, never computed for you.
	const inv = raw.inventory;
	if (!inv || typeof inv !== 'object') {
		fault('missing "inventory" — { chapters, read, skipped }. Spec §3');
	} else {
		const { chapters, read, skipped } = inv;
		if (Number(read) + Number(skipped) !== Number(chapters))
			problems.push(
				`inventory does not balance: read ${read} + skipped ${skipped} !== chapters ${chapters}.\n` +
					'      A chapter was surfaced at Stage 2 and then forgotten — that is exactly\n' +
					'      what the coverage law exists to catch.'
			);
		if (Number(read) !== raw.chapters.length)
			problems.push(
				`inventory.read is ${read} but "chapters" holds ${raw.chapters.length} entries.`
			);
		const anti = Array.isArray(raw.antiChapters) ? raw.antiChapters.length : 0;
		if (Number(skipped) !== anti)
			problems.push(`inventory.skipped is ${skipped} but "antiChapters" holds ${anti} entries.`);
	}

	for (const a of raw.antiChapters ?? [])
		if (!a.reason) fault(`antiChapters "${a.title}" has no reason — and it must be a reason FOR HIM`);

	// Advisory. Reported, never refused: the brief decides how much of a book to
	// read, and the script does not get a veto.
	if (raw.chapters.length > 15 && !(raw.antiChapters ?? []).length)
		advisory(
			`${raw.chapters.length} chapters and an empty antiChapters. That is a table of contents,\n` +
				'      not a decision — but it scaffolds anyway.'
		);
	const est = raw.chapters.reduce((n, c) => n + (Number(c.estMinutes) || 0), 0);
	if (est > 0 && est / 60 > 20)
		advisory(`estimated ${Math.round(est / 60)} hours of reading. The four-week ceiling is a signal, not a rule.`);

	return { problems, warnings };
}

/* ---- the generated regions ---------------------------------------------- */

/*
 * PROSE OUT OF book.json IS UNTRUSTED MDX.
 *
 * A brief is written in a chat session and pasted into JSON, so it can contain a
 * bare `<` or `{` — and md-spec.md §8 records that the two fail DIFFERENTLY:
 * `a <b` is a hard parse error naming the line, while `{threshold}` is a RUNTIME
 * ReferenceError thrown while rendering, so it only fires on a page that has a
 * route. Neither is acceptable in generated output.
 *
 * Entities rather than backticks: a brief sentence is prose, and wrapping half of
 * it in code voice to make it compile would change how it reads. `&lt;` and
 * `&#123;` render as the character and are inert to both MDX and JSX.
 */
const safeProse = (v) =>
	String(v ?? '')
		.replace(/</g, '&lt;')
		.replace(/\{/g, '&#123;')
		.replace(/\}/g, '&#125;')
		.trim();

/**
 * The two sections of the book page that book.json already decided.
 *
 * A MISSING FIELD KEEPS ITS TODO rather than emitting an empty heading. An empty
 * section under a heading claims the question was answered; a TODO says it was
 * not, and that is the difference this whole project keeps insisting on.
 *
 * `outsideView` WAS A THIRD SECTION UNTIL 2026-09-14. The book page now carries
 * `## Context then vs. context today`, written with sources by P2b
 * (context/book-spec.md section 6), which is the long form of the same
 * judgement — restating the three-line digest beside it would be a second,
 * thinner copy of one decision, and the thinner copy is the one that goes stale.
 */
function briefBlock(book) {
	const q = Array.isArray(book.questions) ? book.questions : [];
	const or = (v, todo) => (safeProse(v) ? safeProse(v) : todo);
	const out = [
		BRIEF_START,
		'',
		'## Why this book, now',
		'',
		or(book.whyNow, 'TODO — one paragraph. The problem that made this the next book rather than an easier one.'),
		'',
		'## Questions I brought to it',
		'',
		'{/* Written BEFORE reading, in the inspectional pass. From book.json questions. */}',
		'',
	];
	if (q.length) for (const [i, item] of q.entries()) out.push(`${i + 1}. ${safeProse(item)}`);
	else out.push('1. TODO', '2. TODO', '3. TODO');
	out.push('', BRIEF_END);
	return out.join('\n');
}

function outlineBlock(ch, book, part, number) {
	/*
	 * NEVER WRITE A LITERAL "hash hash space Heading" INSIDE THIS COMMENT.
	 * stamp() removes the clarified section by indexOf on the heading text, and
	 * an occurrence inside this block matches FIRST — which gutted the comment
	 * and left the section, silently, with a green build. Headings are named
	 * here in prose instead.
	 */
	const out = [
		OUTLINE_START,
		'{/* THE BRIEF DECIDED THIS. Generation fills prose into it, and never invents it.',
		'',
		`   book        ${safeComment(book.title)}${book.author ? ` — ${safeComment(book.author)}` : ''}`,
		`   chapter     ${safeComment(displayTitle(ch, number))}   (position ${ch.order} in the book)`,
		part
			? `   part        ${safeComment(part.title)} — ${safeComment(part.outcome)}`
			: '   part        (none)',
		`   argues      ${safeComment(ch.argues)}`,
		`   weight      ${ch.weightInArgument ?? 'unstated'} in the book's argument`,
		`   verdict     ${ch.verdict ?? 'unstated'}`,
		`   estimate    ${ch.estMinutes ?? '?'} min`,
		`   clarified   ${ch.clarified}`,
		'',
	];
	if (ch.clarified) {
		out.push('   clarified true, so the clarified-chapter section is present and gets written.');
	} else {
		out.push('   clarified false, so the clarified-chapter section has been REMOVED from this');
		out.push('   file entirely. READ I is the original text. On familiar material a summary');
		out.push('   preserves the idea and deletes the machinery that made it actionable.');
	}
	out.push('');
	out.push(
		`   gap         ${book.gap} — ${
			book.gap === 'execution'
				? 'reading will not fix a doing problem. Weight the actions, trim the explanation.'
				: 'a knowledge gap. The explanation layer carries real weight here.'
		}`
	);
	out.push('');
	out.push('   The reader writes the recall section CLOSED BOOK, before reading the');
	out.push('   explanation layer, and fills the open-questions section by hand.');
	out.push('   Never write in either. */}');
	out.push(OUTLINE_END);
	return out.join('\n');
}


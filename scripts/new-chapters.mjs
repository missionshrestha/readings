/* ---- refresh needs no book.json and writes no chapter file --------------- */

function readChapterFrontmatter(dir) {
	if (!existsSync(dir)) return [];
	return readdirSync(dir)
		.filter((f) => f.endsWith('.mdx') && f !== 'index.mdx' && !f.startsWith('_'))
		.map((file) => {
			const raw = readFileSync(join(dir, file), 'utf8');
			const open = raw.indexOf('---');
			const close = raw.indexOf('\n---', open + 3);
			const fm = close === -1 ? '' : raw.slice(open + 3, close);
			const f = (n) => {
				const m = fm.match(new RegExp(`^${n}:\\s*(.+)$`, 'm'));
				return m ? m[1].trim().replace(/^["']|["']$/g, '') : undefined;
			};
			const orderM = fm.match(/^\s+order:\s*(\d+)\s*$/m);
			return {
				slug: file.replace(/\.mdx$/, ''),
				title: f('title') ?? file,
				part: f('part') ?? '',
				status: f('status') ?? 'stub',
				draft: f('draft') === 'true',
				order: orderM ? Number(orderM[1]) : Number.POSITIVE_INFINITY,
			};
		})
		.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));
}

/* ---- validation ---------------------------------------------------------- */

function validate(raw) {
	const problems = [];
	const warnings = [];
	const fault = (m) => problems.push(m);
	const advisory = (m) => warnings.push(m);

	if (!raw || typeof raw !== 'object' || Array.isArray(raw))
		return { problems: ['book.json is not an object. See context/book-spec.md §2.'], warnings };

	for (const f of ['slug', 'title', 'kind'])
		if (!raw[f]) fault(`missing "${f}"`);
	if (raw.slug && raw.slug !== bookSlug)
		fault(`"slug" is "${raw.slug}" but the directory is "${bookSlug}" — the path is the truth`);
	if (raw.domain && raw.domain !== domainSlug)
		fault(`"domain" is "${raw.domain}" but the directory says "${domainSlug}"`);
	if (raw.cluster && raw.cluster !== clusterSlug)
		fault(`"cluster" is "${raw.cluster}" but the directory says "${clusterSlug}"`);

	if (!raw.gap) fault('missing "gap" — knowledge or execution. Spec §2, and it comes before everything');
	else if (!GAPS.includes(raw.gap)) fault(`"gap" is "${raw.gap}", must be ${GAPS.join(' or ')}`);

	if (raw.familiarity && !FAMILIARITY.includes(raw.familiarity))
		fault(`"familiarity" is "${raw.familiarity}", must be one of ${FAMILIARITY.join(', ')}`);

	if (!raw.exitCondition) fault('missing "exitCondition" — what must be TRUE for this book to be finished');
	if (!Array.isArray(raw.questions) || raw.questions.length < 3)
		fault('"questions" needs 3-5 entries, written BEFORE reading. Written after, they are a summary');

	if (raw.kind !== 'read') {
		if (raw.chapters?.length) fault(`kind "${raw.kind}" carries no chapters`);
		return { problems, warnings };
	}

	if (!Array.isArray(raw.chapters) || raw.chapters.length === 0)
		return { problems: [...problems, 'no "chapters" array'], warnings };

	const partSlugs = new Set((raw.parts ?? []).map((p) => p.slug));
	for (const p of raw.parts ?? []) {
		if (!KEBAB.test(p.slug ?? '')) fault(`part slug "${p.slug}" is not kebab-case`);
		if (!p.outcome) fault(`part "${p.slug}" has no "outcome"`);
	}

	const seen = new Set();
	const orders = new Set();
	for (const c of raw.chapters) {
		const at = `chapter "${c.slug ?? c.title ?? '?'}"`;
		if (!KEBAB.test(c.slug ?? '')) fault(`${at}: slug is missing or not kebab-case`);
		if (seen.has(c.slug)) fault(`${at}: slug repeats`);
		seen.add(c.slug);
		if (!Number.isInteger(c.order)) fault(`${at}: "order" must be an integer`);
		else if (orders.has(c.order)) fault(`${at}: order ${c.order} repeats`);
		else orders.add(c.order);
		if (!c.title) fault(`${at}: no title`);
		if (!c.argues) fault(`${at}: no "argues" — one line, a CLAIM rather than a topic`);
		if (c.part && !partSlugs.has(c.part)) fault(`${at}: part "${c.part}" is not in "parts"`);
		if (c.verdict && !VERDICTS.includes(c.verdict))
			fault(`${at}: verdict "${c.verdict}", must be one of ${VERDICTS.join(', ')}`);
		if (c.verdict === 'skip')
			fault(`${at}: verdict "skip" — a skipped chapter belongs in "antiChapters", not "chapters"`);
		if (c.weightInArgument && !WEIGHTS_IN_ARG.includes(c.weightInArgument))
			fault(`${at}: weightInArgument "${c.weightInArgument}", must be one of ${WEIGHTS_IN_ARG.join(', ')}`);
		if (typeof c.clarified !== 'boolean')
			fault(`${at}: "clarified" must be true or false — a deliberate value, not a default nobody looked at`);
	}

	// THE COVERAGE LAW. Asserted, never computed for you.
	const inv = raw.inventory;
	if (!inv || typeof inv !== 'object') {
		fault('missing "inventory" — { chapters, read, skipped }. Spec §3');
	} else {
		const { chapters, read, skipped } = inv;
		if (Number(read) + Number(skipped) !== Number(chapters))
			problems.push(
				`inventory does not balance: read ${read} + skipped ${skipped} !== chapters ${chapters}.\n` +
					'      A chapter was surfaced at Stage 2 and then forgotten — that is exactly\n' +
					'      what the coverage law exists to catch.'
			);
		if (Number(read) !== raw.chapters.length)
			problems.push(
				`inventory.read is ${read} but "chapters" holds ${raw.chapters.length} entries.`
			);
		const anti = Array.isArray(raw.antiChapters) ? raw.antiChapters.length : 0;
		if (Number(skipped) !== anti)
			problems.push(`inventory.skipped is ${skipped} but "antiChapters" holds ${anti} entries.`);
	}

	for (const a of raw.antiChapters ?? [])
		if (!a.reason) fault(`antiChapters "${a.title}" has no reason — and it must be a reason FOR HIM`);

	// Advisory. Reported, never refused: the brief decides how much of a book to
	// read, and the script does not get a veto.
	if (raw.chapters.length > 15 && !(raw.antiChapters ?? []).length)
		advisory(
			`${raw.chapters.length} chapters and an empty antiChapters. That is a table of contents,\n` +
				'      not a decision — but it scaffolds anyway.'
		);
	const est = raw.chapters.reduce((n, c) => n + (Number(c.estMinutes) || 0), 0);
	if (est > 0 && est / 60 > 20)
		advisory(`estimated ${Math.round(est / 60)} hours of reading. The four-week ceiling is a signal, not a rule.`);

	return { problems, warnings };
}

/* ---- the generated regions ---------------------------------------------- */

function outlineBlock(ch, book, part) {
	/*
	 * NEVER WRITE A LITERAL "hash hash space Heading" INSIDE THIS COMMENT.
	 * stamp() removes the clarified section by indexOf on the heading text, and
	 * an occurrence inside this block matches FIRST — which gutted the comment
	 * and left the section, silently, with a green build. Headings are named
	 * here in prose instead.
	 */
	const out = [
		OUTLINE_START,
		'{/* THE BRIEF DECIDED THIS. Generation fills prose into it, and never invents it.',
		'',
		`   book        ${safeComment(book.title)}${book.author ? ` — ${safeComment(book.author)}` : ''}`,
		`   chapter     ${ch.order} · ${safeComment(ch.title)}`,
		part
			? `   part        ${safeComment(part.title)} — ${safeComment(part.outcome)}`
			: '   part        (none)',
		`   argues      ${safeComment(ch.argues)}`,
		`   weight      ${ch.weightInArgument ?? 'unstated'} in the book's argument`,
		`   verdict     ${ch.verdict ?? 'unstated'}`,
		`   estimate    ${ch.estMinutes ?? '?'} min`,
		`   clarified   ${ch.clarified}`,
		'',
	];
	if (ch.clarified) {
		out.push('   clarified true, so the clarified-chapter section is present and gets written.');
	} else {
		out.push('   clarified false, so the clarified-chapter section has been REMOVED from this');
		out.push('   file entirely. READ I is the original text. On familiar material a summary');
		out.push('   preserves the idea and deletes the machinery that made it actionable.');
	}
	out.push('');
	out.push(
		`   gap         ${book.gap} — ${
			book.gap === 'execution'
				? 'reading will not fix a doing problem. Weight the actions, trim the explanation.'
				: 'a knowledge gap. The explanation layer carries real weight here.'
		}`
	);
	out.push('');
	out.push('   The reader writes the recall section CLOSED BOOK, before reading the');
	out.push('   explanation layer, and fills the open-questions section by hand.');
	out.push('   Never write in either. */}');
	out.push(OUTLINE_END);
	return out.join('\n');
}

/**
 * THE TEN SUB-SECTIONS OF THE EXPLANATION LAYER. Fixed by context/chapter-spine.md.
 *
 * TEN, not nine. `### Where the author was standing` was added 2026-08-31 on his
 * own instruction, given unprompted in the reader interview: "everyone's thought
 * is inspired, derived from their own circumstances, so that can help understand
 * what writer/author actually meant and why" (context/reader.md section 4c).
 *
 * It is FIRST, and inside the explanation layer rather than in `## Pre-context`,
 * for three reasons that are written out in full in chapter-spine.md section 1:
 * P4 is unconditional while P3 is not; it sits immediately before the claim it
 * contextualises; and the explanation layer is read AFTER the closed-book recall,
 * so author context cannot frame — and bias — the retrieval.
 */
const EXPLANATION = [
	[
		'Where the author was standing',
		'Who they were, when, what problem they were living inside, what they were reacting against — and what that predicts about where the argument bends. NOT biography, and it never explains the argument away.',
	],
	['What the author is actually saying', 'The argument, stated more plainly than the chapter states it.'],
	['Where readers get confused', 'The specific misreadings, not "some find it difficult".'],
	['The teaching pass', 'The mechanism, taught rather than summarised.'],
	['What real readers say', 'From actual threads. If it is thin, SAY SO — never manufacture consensus.'],
	['What critics say', 'The strongest case against, argued properly.'],
	["What's been tested since", 'Replication, later evidence, what has failed to hold.'],
	['How practitioners actually use it', 'What people who operate this do, at a stated scale.'],
	[
		"Where it doesn't transfer",
		'Where the CLAIM\'S CONDITIONS differ — economics, institutions, country, stage of life. Describe the difference; never conclude that it therefore does not apply to him. That conclusion is his, and it belongs with the recall. ADD, never subtract.',
	],
	['The version to hold', 'The synthesis. What survives all nine sections above.'],
];

function spineBlock() {
	const out = [SPINE_START];
	for (const [title, note] of EXPLANATION) {
		out.push('');
		out.push(`### ${title}`);
		out.push('');
		out.push(`{/* ${safeComment(note)} */}`);
		out.push('');
		out.push('TODO');
	}
	out.push('');
	out.push(SPINE_END);
	return out.join('\n');
}

function stamp(template, ch, book, part) {
	const end = template.indexOf('\n---', 4);
	let body = template.slice(end + 4);

	const lines = [
		'---',
		`title: ${yaml(`Ch ${ch.order} · ${ch.title}`)}`,
		`description: ${yaml(ch.argues)}`,
		'sidebar:',
		`  order: ${ch.order}`,
		`book: ${book.slug}`,
	];
	if (book.author) lines.push(`author: ${yaml(book.author)}`);
	lines.push(
		`domain: ${domainSlug}`,
		`cluster: ${clusterSlug}`,
		`chapter: ${ch.order}`
	);
	if (ch.part) lines.push(`part: ${yaml(ch.part)}`);
	lines.push(
		`kind: ${book.kind}`,
		`tier: ${book.tier ?? 'core'}`,
		`weight: ${book.weight ?? 'M'}`,
		`gap: ${book.gap}`,
		`clarified: ${ch.clarified}`
	);
	if (ch.verdict) lines.push(`verdict: ${ch.verdict}`);
	lines.push('status: stub');
	// `status: stub` and `draft: true` TRAVEL TOGETHER. That pairing is the
	// safety property of the whole system: visible in dev, absent from build, so
	// an unwritten chapter cannot reach the public site.
	lines.push('draft: true');
	lines.push('private: false');
	if (ch.estMinutes) lines.push(`# estMinutes: ${ch.estMinutes}`);
	if (ch.weightInArgument) lines.push(`# weightInArgument: ${ch.weightInArgument}`);
	lines.push('---');

	body = replaceRegion(body, OUTLINE_START, OUTLINE_END, outlineBlock(ch, book, part)) ?? body;
	body = replaceRegion(body, SPINE_START, SPINE_END, spineBlock()) ?? body;

	/*
	 * clarified: false -> the section is not merely empty, it is ABSENT.
	 *
	 * Anchored on a NEWLINE followed by the heading, never a bare indexOf: the
	 * generated comment above discusses these sections by name, and a bare
	 * indexOf matched inside the comment and destroyed it instead. Loud enough
	 * to find once, silent enough to ship if nobody checks.
	 */
	if (!ch.clarified) {
		const from = body.indexOf('\n## The clarified chapter');
		const to = body.indexOf('\n## Recall');
		if (from !== -1 && to !== -1 && to > from) body = body.slice(0, from) + body.slice(to);
		else
			console.warn(
				`  warning: ${ch.slug} is clarified:false but the section could not be located.`
			);
	}
	return lines.join('\n') + body;
}

/* ---- the chapter grid on the book index --------------------------------- */

function chaptersBlock(book, onDisk) {
	const byPart = new Map();
	for (const ch of onDisk) {
		const key = ch.part ?? '';
		if (!byPart.has(key)) byPart.set(key, []);
		byPart.get(key).push(ch);
	}
	const partTitle = new Map((book.parts ?? []).map((p) => [p.slug, p]));
	const base = `/${domainSlug}/${clusterSlug}/${bookSlug}`;

	const out = [CHAPTERS_START, '', '## Chapters', ''];
	for (const [key, items] of byPart) {
		const p = partTitle.get(key);
		if (p) {
			out.push(`### ${p.title}`);
			out.push('');
			out.push(p.outcome);
			out.push('');
		}
		const written = items.filter((c) => !c.draft).length;
		out.push(`<p class="rd-partmeta">${written} of ${items.length} written</p>`);
		out.push('');
		out.push('<CardGrid>');
		/*
		 * THE ORDER PREFIX IS SKIPPED WHEN THE TITLE ALREADY CARRIES ONE.
		 *
		 * chapter-spine.md has a chapter title begin "Ch N · …", so prefixing the
		 * order gave "1. Ch 1 · Deep work is valuable" on every card of every
		 * book index. Same rule and same regex as bookSidebar() in
		 * scripts/universe.mjs, which fixes the drawer and the pagination pair —
		 * they have to agree, or the card and the sidebar entry for one chapter
		 * disagree on its own name.
		 */
		const SELF_NUMBERED = /^(?:ch(?:apter)?\.?\s*)?\d+\s*[·.:—–-]/i;
		const cardTitle = (c) =>
			Number.isFinite(c.order) && !SELF_NUMBERED.test(c.title)
				? `${c.order}. ${c.title}`
				: c.title;
		for (const c of items) {
			// THE THREE-WAY COLLISION, and its only resolution:
			//   1. a stub carries draft: true, so it never reaches the public site
			//   2. the index should show the WHOLE chapter map, written or not
			//   3. the link validator FAILS THE BUILD on a link to a page that does
			//      not exist — and a draft page does not exist in `build`
			// So: a real link when written, a plain card carrying a badge when not.
			if (c.draft) {
				out.push(`  <Card title=${yaml(cardTitle(c))}>`);
				out.push(`    <Badge text="Not written" variant="default" size="small" />`);
				out.push('  </Card>');
			} else {
				out.push(
					`  <LinkCard title=${yaml(cardTitle(c))} href=${yaml(`${base}/${c.slug}/`)} />`
				);
			}
		}
		out.push('</CardGrid>');
		out.push('');
	}
	if (book.antiChapters?.length) {
		out.push('### Deliberately skipped');
		out.push('');
		out.push('Not an omission. Each of these was surfaced at the brief and cut, with a reason.');
		out.push('');
		for (const a of book.antiChapters) out.push(`- **${a.title}** — ${a.reason}`);
		out.push('');
	}
	out.push(CHAPTERS_END);
	return out.join('\n');
}

function writeIndexGrid(book, onDisk) {
	let index = readFileSync(indexPath, 'utf8');

	/*
	 * MERGE the names this block needs into whatever import line already exists,
	 * rather than testing for one name and assuming the rest.
	 *
	 * The first version checked `index.includes('CardGrid')` and skipped the
	 * injection when it matched. The book template imports CardGrid but NOT Card,
	 * so the check passed, Card was never imported, and the build failed at
	 * RENDER time with "Expected component Card to be defined" — long after the
	 * scaffold reported success.
	 */
	const NEEDED = ['Aside', 'Badge', 'Card', 'CardGrid', 'LinkCard'];
	const SL = /import\s*\{([^}]*)\}\s*from\s*'@astrojs\/starlight\/components';/;
	const found = index.match(SL);
	if (found) {
		const have = found[1].split(',').map((n) => n.trim()).filter(Boolean);
		const merged = [...new Set([...have, ...NEEDED])].sort();
		index = index.replace(
			SL,
			`import { ${merged.join(', ')} } from '@astrojs/starlight/components';`
		);
	} else {
		const fmEnd = index.indexOf('\n---', 4) + 4;
		index =
			index.slice(0, fmEnd) +
			`\nimport { ${NEEDED.join(', ')} } from '@astrojs/starlight/components';\n` +
			index.slice(fmEnd);
	}
	const block = chaptersBlock(book, onDisk);
	const replaced = replaceRegion(index, CHAPTERS_START, CHAPTERS_END, block);
	index = replaced ?? index.trimEnd() + '\n\n' + block + '\n';
	writeFileSync(indexPath, index);
	return replaced === null ? 'appended (markers were absent)' : 'replaced';
}


/*
 * THE CHAPTER'S `description` IS DERIVED FROM `argues`, AND --outline DID NOT
 * CARRY IT.
 *
 * Line 362 of this file writes `description: <argues>` at scaffold time, so the
 * two are one field with two homes. --outline rewrote the OUTLINE region and
 * nothing else, so amending a brief updated the comment block on the page and
 * left the description alone.
 *
 * MEASURED 2026-09-04: six Deep Work chapters were scaffolded from a placeholder
 * brief, the brief was replaced with real `argues` lines, --outline was run, and
 * all six pages kept `description: "PLACEHOLDER — the claim this chapter makes,
 * in one line."` — which is the page's <meta name="description">, its search
 * snippet and what a reader sees before they open it. Green build, correct
 * OUTLINE region, wrong description, and nothing said so.
 *
 * IT PRINTS EVERY CHANGE RATHER THAN MAKING THEM QUIETLY. A description may have
 * been improved by hand during a paste, and silently discarding that would be the
 * same defect in the other direction — so each rewrite is named with its old and
 * new value, and the reader can see what the amendment cost.
 */
function syncDescription(text, ch) {
	const fmEnd = text.indexOf('\n---', 4);
	if (fmEnd === -1) return { text, from: null };
	const head = text.slice(0, fmEnd);
	const m = head.match(/^description:[ \t]*(.+)$/m);
	const want = `description: ${yaml(ch.argues)}`;
	if (!m || m[0] === want) return { text, from: null };
	return { text: head.replace(m[0], want) + text.slice(fmEnd), from: m[1].trim() };
}

/*
 * THE TITLE, `chapter` AND `label` ARE DERIVED TOO, since 2026-09-15.
 *
 * Giving an Introduction its `label` after the chapters were scaffolded changes
 * the site's number of every chapter after it — back to the book's own. This is
 * how that reaches pages that already exist: the title is re-derived from the
 * label or the number, `chapter:` is written only on a numbered chapter and
 * `label:` only on a labelled one. Every title change is PRINTED, for the same
 * reason syncDescription() prints: a hand edit discarded quietly is the same
 * defect in the other direction.
 */
function syncNumbering(text, ch, number) {
	const fmEnd = text.indexOf('\n---', 4);
	if (fmEnd === -1) return { text, from: null };
	let head = text.slice(0, fmEnd);
	const t = head.match(/^title:[ \t]*(.+)$/m);
	const wantTitle = `title: ${yaml(displayTitle(ch, number))}`;
	const from = t && t[0] !== wantTitle ? t[1].trim() : null;
	if (t) head = head.replace(t[0], wantTitle);
	// Drop both top-level keys, then write back the one this chapter has, after `cluster:`.
	head = head.replace(/^(?:chapter|label):[^\n]*\n?/gm, '');
	const want = ch.label ? `label: ${yaml(String(ch.label).trim())}` : `chapter: ${number}`;
	const c = head.match(/^cluster:[^\n]*$/m);
	head = c ? head.replace(c[0], `${c[0]}\n${want}`) : `${head}\n${want}`;
	return { text: head + text.slice(fmEnd), from };
}


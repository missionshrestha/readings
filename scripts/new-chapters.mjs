const template = readFileSync(TEMPLATE, 'utf8');
const chapters = [...raw.chapters].sort((a, b) => a.order - b.order);
const partBySlug = new Map((raw.parts ?? []).map((p) => [p.slug, p]));

if (SPINE_ONLY) {
	/*
	 * A region is "untouched" when every line between the markers is either
	 * blank, a heading, a generated comment, or the literal TODO. One authored
	 * word anywhere in it and the file is left alone.
	 */
	const untouched = (region) =>
		region
			.split('\n')
			.every(
				(l) =>
					l.trim() === '' ||
					l.startsWith('### ') ||
					l.trim().startsWith('{/*') ||
					l.trim() === 'TODO'
			);

	let rewritten = 0;
	const skipped = [];
	for (const ch of chapters) {
		const file = join(bookDir, `${ch.slug}.mdx`);
		if (!existsSync(file)) { skipped.push(`${ch.slug}.mdx (no such file)`); continue; }
		const text = readFileSync(file, 'utf8');
		const from = text.indexOf(SPINE_START);
		const to = text.indexOf(SPINE_END);
		if (from === -1 || to === -1) { skipped.push(`${ch.slug}.mdx (SPINE markers gone)`); continue; }
		const inner = text.slice(from + SPINE_START.length, to);
		if (!untouched(inner)) {
			skipped.push(`${ch.slug}.mdx (WRITTEN IN — the explanation layer has content)`);
			continue;
		}
		writeFileSync(file, replaceRegion(text, SPINE_START, SPINE_END, spineBlock()));
		rewritten++;
	}
	console.log(`\n  --spine: rewrote the explanation-layer region in ${rewritten} stub(s)\n`);
	if (skipped.length) {
		console.log('  SKIPPED, and named rather than silently passed over:');
		for (const m of skipped) console.log(`    · ${m}`);
		console.log('\n  A chapter that has been written in keeps what it has. Bring a spine change');
		console.log('  to those by hand, or regenerate the chapter from the brief.\n');
	}
	process.exit(0);
}

if (OUTLINE_ONLY) {
	let rewritten = 0;
	const missing = [];
	for (const ch of chapters) {
		const file = join(bookDir, `${ch.slug}.mdx`);
		if (!existsSync(file)) { missing.push(`${ch.slug}.mdx (no such file)`); continue; }
		let text = readFileSync(file, 'utf8');
		const a = replaceRegion(text, OUTLINE_START, OUTLINE_END, outlineBlock(ch, raw, partBySlug.get(ch.part)));
		if (a === null) { missing.push(`${ch.slug}.mdx (OUTLINE markers gone)`); continue; }
		writeFileSync(file, a);
		rewritten++;
	}
	console.log(`\n  --outline: rewrote the generated region in ${rewritten} file(s)\n`);
	if (missing.length) {
		console.log('  SKIPPED, and named rather than silently passed over:');
		for (const m of missing) console.log(`    · ${m}`);
		console.log('\n  An amendment that did not reach the page is an amendment that did not happen.\n');
	}
	writeIndexGrid(raw, readChapterFrontmatter(bookDir));
	process.exit(0);
}

// All-or-nothing.
const targets = chapters.map((ch) => join(bookDir, `${ch.slug}.mdx`));
const existing = targets.filter((t) => existsSync(t));
if (existing.length) {
	console.error(`\n  ${existing.length} chapter file(s) already exist. The WHOLE run is refused,`);
	console.error('  so it cannot half-apply and leave the book in a state nobody can reason about.\n');
	for (const e of existing) console.error(`    · ${e.replace(ROOT + '/', '')}`);
	console.error('\n  To push an amended book.json into stubs that already exist, use --outline.\n');
	process.exit(1);
}


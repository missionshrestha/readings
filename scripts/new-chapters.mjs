/**
 * new-chapters.mjs — turn an agreed book.json into one stub per chapter.
 *
 *   node scripts/new-chapters.mjs <domain> <cluster> <book>             scaffold
 *   node scripts/new-chapters.mjs <domain> <cluster> <book> --refresh   after a paste
 *   node scripts/new-chapters.mjs <domain> <cluster> <book> --outline   after an amendment
 *
 * ---------------------------------------------------------------------------
 * EVERYTHING IS VALIDATED BEFORE ANY FILE IS WRITTEN
 *
 * book.json arrives by PASTE from a session that cannot see this filesystem, so
 * a missing field is the EXPECTED case rather than an edge case. Every problem
 * is collected and printed at once — taking one error at a time back to web chat
 * costs a round trip per field.
 *
 * ---------------------------------------------------------------------------
 * THE MARKER REGIONS
 *
 * Two per chapter stub, one in the book index. Each is replaced by byte-scoped
 * indexOf surgery whose primitive returns NULL rather than throwing — which is
 * what lets --outline SKIP AND NAME a file whose markers a paste destroyed,
 * instead of silently doing nothing.
 *
 * A star-slash inside an MDX comment closes it early, and that defect has
 * already cost the sibling project a build IN THE VERY LINE EXPLAINING HOW TO
 * WRITE A COMMENT. safeComment() rewrites it as a VISIBLE break, never a
 * zero-width one nobody can see.
 *
 * ---------------------------------------------------------------------------
 * ALL-OR-NOTHING
 *
 * The default mode refuses the whole run if ANY target exists, so a re-run
 * cannot half-apply and leave the book in a state nobody can reason about.
 * --outline is the single deliberate exception and is confined to the markers.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseUniverse } from './universe.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = join(ROOT, 'src', 'content', 'docs');
const TEMPLATE = join(ROOT, 'context', 'templates', '_TEMPLATE-CHAPTER.mdx');

const OUTLINE_START =
	'{/* OUTLINE:START — generated by scripts/new-chapters.mjs from book.json. Do not edit by hand. */}';
const OUTLINE_END = '{/* OUTLINE:END */}';
const SPINE_START =
	'{/* SPINE:START — generated by scripts/new-chapters.mjs from book.json. Do not edit by hand. */}';
const SPINE_END = '{/* SPINE:END */}';
const CHAPTERS_START =
	'{/* CHAPTERS:START — generated by scripts/new-chapters.mjs. Do not edit by hand. */}';
const CHAPTERS_END = '{/* CHAPTERS:END */}';

const KEBAB = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const VERDICTS = ['deep-dive', 'skim', 'skip'];
const WEIGHTS_IN_ARG = ['load-bearing', 'supporting', 'illustrative'];
const GAPS = ['knowledge', 'execution'];
const FAMILIARITY = ['new', 'familiar', 'expert'];

/** Replace the bytes between a marker pair. NULL when the pair is gone. */
function replaceRegion(text, start, end, replacement) {
	const a = text.indexOf(start);
	const b = text.indexOf(end);
	if (a === -1 || b === -1 || b < a) return null;
	return text.slice(0, a) + replacement + text.slice(b + end.length);
}

/** A star-slash inside an MDX comment closes it early. Break it VISIBLY. */
const safeComment = (s) =>
	String(s)
		.replace(/\*\//g, '* /')
		.replace(/\r?\n/g, ' ')
		.trim();

const yaml = (v) => JSON.stringify(String(v));

